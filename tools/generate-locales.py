"""Validate the editable English catalog and generate the compiled lookup table."""
from pathlib import Path
import argparse,json,re,sys
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
data=json.loads((root/'locales/en.json').read_text(encoding='utf-8'))
assert data['format']=='ccrIDE.translations' and data['schema']==1 and data['language']=='en'
messages=data['messages'];keys=set()
# Exact printf argument sequence, including integer length modifiers, must match.
formats=re.compile(r'%(?:\d+\$)?[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')
for source,target in messages.items():
    assert isinstance(target,str) and target,repr(source)
    assert formats.findall(source)==formats.findall(target),f'Format mismatch: {source!r}'
    assert source.count('\0')==target.count('\0'),f'Combo item mismatch: {source!r}'
    key=source.split('\0',1)[0];assert key not in keys,f'Duplicate runtime key: {key}';keys.add(key)
def cpp(text):return json.dumps(text,ensure_ascii=False).replace('\\u0000','\\0')
output='// Generated by tools/generate-locales.py. Edit locales/en.json instead.\n'+''.join('{'+cpp(k)+','+cpp(v)+'},\n' for k,v in sorted(messages.items()))
path=root/'src/i18n_catalog.inc'
if args.check:
    if path.read_text(encoding='utf-8')!=output:raise SystemExit('Catalog is out of date; run tools/generate-locales.py')
else:path.write_text(output,encoding='utf-8')
print(f'{len(messages)} translations validated')
